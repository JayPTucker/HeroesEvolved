"""The Wither's cage: original blackstone containment amphitheatre. Regenerates its blueprint; no valuable ore."""
from pathlib import Path
import math
from blueprint_draft import StateGrid

ROOT = Path(__file__).resolve().parents[1]
g = StateGrid(85, 55, 89, fill='minecraft:air')
def put(x, y, z, block):
    g.put(x + 42, y, z + 43, block if ':' in block else 'minecraft:' + block)
def box(x0, y0, z0, x1, y1, z1, block):
    for x in range(x0, x1 + 1):
        for y in range(y0, y1 + 1):
            for z in range(z0, z1 + 1): put(x, y, z, block)

# A thick, continuous foundation; the broad outer drum joins the ribs instead of leaving scenery floating.
for x in range(-40, 41):
    for z in range(-40, 41):
        r = math.hypot(x, z)
        if r > 40: continue
        put(x, 0, z, 'polished_blackstone_bricks')
        put(x, 1, z, 'blackstone')
        angle = math.atan2(z, x)
        spoke = abs(math.sin(angle * 6)) < .08 and r > 4
        floor = 'polished_basalt @wither:channel' if spoke else 'polished_blackstone' if r < 8 or 32 < r < 34 else 'polished_blackstone_bricks'
        if r > 38: floor = 'chiseled_polished_blackstone'
        put(x, 2, z, floor)
        if 38.3 < r < 39.5:
            put(x, 3, z, 'polished_blackstone_bricks')
            if (x*x + z*z) % 5 != 0: put(x, 4, z, 'cracked_polished_blackstone_bricks')
        if (x % 6 == 0 and z % 6 == 0):
            put(x, 2, z, 'sea_lantern')

# Twelve rooted fossil ribs rise in courses and bend toward the hungry center. Course overlap gives each a real root.
for i in range(12):
    angle = i * math.tau / 12
    for y in range(3, 51):
        radius = 38 - max(0, y - 22) * .38
        cx, cz = round(math.cos(angle) * radius), round(math.sin(angle) * radius)
        for x in range(cx - 1, cx + 2):
            for z in range(cz - 1, cz + 2):
                if x*x + z*z < 40*40: put(x, y, z, 'bone_block[axis=y]' if (x+z+y) % 5 else 'calcite')
        if y % 3 == 0:
            for dx,dz in [(-1,0),(1,0),(0,-1),(0,1)]:put(cx+dx,y,cz+dz,'sea_lantern')
    cx, cz = round(math.cos(angle)*38), round(math.sin(angle)*38)
    box(cx-1, 3, cz-1, cx+1, 5, cz+1, 'polished_blackstone_bricks')

# Four pillars are genuinely solid cover for the star discharge. Their caps and foundations give them depth.
for x, z in [(-17,-14), (17,-14), (-17,14), (17,14)]:
    box(x-2, 3, z-2, x+2, 3, z+2, 'chiseled_polished_blackstone')
    box(x-1, 4, z-1, x+1, 16, z+1, 'polished_blackstone_bricks')
    box(x-2, 17, z-2, x+2, 17, z+2, 'polished_blackstone')
    put(x, 18, z, 'sea_lantern')

# Three anchors, one per head. Coordinates are shared with WitherGeometry and checked by a game test.
anchors = [(-24, 8), (24, 8), (0, -27)]
for i, (x,z) in enumerate(anchors):
    box(x-2, 3, z-2, x+2, 3, z+2, 'polished_blackstone')
    box(x-1, 4, z-1, x+1, 4, z+1, 'chiseled_polished_blackstone')
    put(x, 5, z, 'sea_lantern')
    put(x, 6, z, f'minecraft:tinted_glass @anchor:{i}')
    for dx,dz in [(-1,0),(1,0),(0,-1),(0,1)]:
        put(x+dx, 5, z+dz, 'polished_blackstone_bricks')
        put(x+dx, 6, z+dz, 'polished_blackstone_bricks')
    put(x, 7, z, 'chiseled_polished_blackstone')

# Return alcove, behind a real sight-breaking baffle, with a clear path on either side.
box(-4, 0, -41, 4, 2, -33, 'polished_blackstone_bricks')
box(-3, 3, -41, 3, 7, -41, 'polished_blackstone_bricks')
box(-4, 3, -41, -4, 7, -34, 'polished_blackstone_bricks')
box(4, 3, -41, 4, 7, -34, 'polished_blackstone_bricks')
box(-4, 8, -41, 4, 8, -34, 'polished_blackstone')
box(-1, 3, -34, 1, 6, -34, 'polished_blackstone_bricks')
put(-3, 6, -38, 'sea_lantern'); put(3, 6, -38, 'sea_lantern')
put(0, 10, 0, 'minecraft:air @spawn:wither')
put(7, 3, -31, 'minecraft:air @spawn:fighter')

g.write(ROOT / 'src/main/resources/data/heroesevolved/blueprints/wither_cage.blueprint',
        name='wither_cage', anchor=(42, 0, 43),
        notes=['Generated by tools/generate-wither-arena.py. Floor at y=2, fighters at y=3. All ribs rooted.',
               '81 blocks across, 46 blocks of usable flight height. Outer ribs rise 48 blocks above the floor.',
               'WitherGeometry: anchors (-24,6,8), (24,6,8), (0,6,-27); return (0,4,-38).'])
