package com.jayptucker.heroesevolved.endportal;

import com.google.gson.JsonParser;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.EndPortalFrameBlock;
import net.minecraft.world.phys.Vec3;

import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

/** The actual frame, the payment's timing and the drawing all share these numbers. Generated by tools/balance.py. */
public final class PortalGeometry {
    public static final int MINIMUM_LEVEL, CHANNEL_TICKS, MEMORY_TICKS, OPEN_TICKS;
    public static final double START_FRACTION;
    private static final List<BlockPos> FRAMES = frames();
    static {
        try (var input = PortalGeometry.class.getResourceAsStream("/data/heroesevolved/end_portal_ritual.json")) {
            if (input == null) throw new IllegalStateException("Missing End portal tuning");
            var data = JsonParser.parseReader(new InputStreamReader(input, StandardCharsets.UTF_8)).getAsJsonObject();
            MINIMUM_LEVEL = data.get("minimum_power_level").getAsInt();
            CHANNEL_TICKS = data.get("channel_ticks").getAsInt();
            MEMORY_TICKS = data.get("memory_ticks").getAsInt();
            OPEN_TICKS = data.get("opening_ticks").getAsInt();
            START_FRACTION = data.get("starting_stamina_fraction").getAsDouble();
            if (MINIMUM_LEVEL < 1 || MINIMUM_LEVEL > 20 || CHANNEL_TICKS < 20 || MEMORY_TICKS < CHANNEL_TICKS
                    || OPEN_TICKS < 1 || !Double.isFinite(START_FRACTION) || START_FRACTION <= 0 || START_FRACTION > 1)
                throw new IllegalStateException("Invalid End portal tuning");
        } catch (java.io.IOException e) { throw new ExceptionInInitializerError(e); }
    }

    private PortalGeometry() {}

    private static List<BlockPos> frames() {
        List<BlockPos> result = new ArrayList<>();
        // Ordered round the perimeter, with the missing corner cells deliberately left out.
        for (int x = -1; x <= 1; x++) result.add(new BlockPos(x, 0, -2));
        for (int z = -1; z <= 1; z++) result.add(new BlockPos(2, 0, z));
        for (int x = 1; x >= -1; x--) result.add(new BlockPos(x, 0, 2));
        for (int z = 1; z >= -1; z--) result.add(new BlockPos(-2, 0, z));
        return List.copyOf(result);
    }

    public static List<BlockPos> frames(BlockPos center) { return FRAMES.stream().map(center::offset).toList(); }

    public static boolean loaded(ServerLevel level, BlockPos center) {
        for (int x : new int[] {-2, 2}) for (int z : new int[] {-2, 2})
            if (!level.hasChunkAt(center.offset(x, 0, z))) return false;
        return true;
    }

    public static Direction facing(BlockPos offset) {
        if (offset.getX() == -2) return Direction.EAST;
        if (offset.getX() == 2) return Direction.WEST;
        return offset.getZ() == -2 ? Direction.SOUTH : Direction.NORTH;
    }

    public static boolean complete(ServerLevel level, BlockPos center) {
        if (!loaded(level, center)) return false;
        for (BlockPos offset : FRAMES) {
            var state = level.getBlockState(center.offset(offset));
            if (!state.is(Blocks.END_PORTAL_FRAME) || !state.getValue(EndPortalFrameBlock.HAS_EYE)
                    || state.getValue(EndPortalFrameBlock.FACING) != facing(offset)) return false;
        }
        return true;
    }

    /** Only twelve nearby candidate centers, never a world-wide search or a read into an unloaded chunk. */
    public static BlockPos center(ServerLevel level, BlockPos frame) {
        if (!level.hasChunkAt(frame) || !level.getBlockState(frame).is(Blocks.END_PORTAL_FRAME)) return null;
        for (BlockPos offset : FRAMES) {
            BlockPos candidate = frame.subtract(offset);
            if (complete(level, candidate)) return candidate;
        }
        return null;
    }

    public static boolean clear(ServerLevel level, BlockPos center) {
        if (!loaded(level, center)) return false;
        for (int x = -1; x <= 1; x++) for (int z = -1; z <= 1; z++) {
            BlockPos at = center.offset(x, 0, z);
            var state = level.getBlockState(at);
            if (!level.getWorldBorder().isWithinBounds(at) || level.getBlockEntity(at) != null
                    || !(state.isAir() || state.canBeReplaced())) return false;
        }
        return true;
    }

    public static boolean open(ServerLevel level, BlockPos center) {
        if (!loaded(level, center)) return false;
        for (int x = -1; x <= 1; x++) for (int z = -1; z <= 1; z++)
            if (level.getBlockState(center.offset(x, 0, z)).is(Blocks.END_PORTAL)) return true;
        return false;
    }

    public static boolean adjacent(BlockPos a, BlockPos b) {
        return a.getY() == b.getY() && a.distManhattan(b) == 1;
    }

    public static BlockPos underfoot(LivingEntity player) {
        return BlockPos.containing(player.getX(), player.getY() - .08, player.getZ());
    }

    public static Vec3 eye(BlockPos frame) { return Vec3.atCenterOf(frame).add(0, .55, 0); }
    public static Vec3 surface(BlockPos center) { return Vec3.atCenterOf(center).add(0, .28, 0); }

    /** A floating receiving iris just inside the frame keeps palms and streams clear of the caster's legs. */
    public static Vec3 focus(Vec3 eye, Vec3 center) {
        return eye.add(center.subtract(eye).multiply(1, 0, 1).normalize().scale(.65)).add(0, .85, 0);
    }

    public static boolean standing(LivingEntity player, BlockPos frame, BlockPos center) {
        if (!underfoot(player).equals(frame) || player.isPassenger() || Math.abs(player.getY() - frame.getY() - 1) > .23)
            return false;
        Vec3 toward = surface(center).subtract(player.getEyePosition()).normalize();
        return player.getLookAngle().dot(toward) > .55;
    }

    /** Two hands reaching down together: the same shoulder and arm length as the player model. */
    public static Vec3 hand(LivingEntity player, Vec3 feet, Vec3 target, boolean right, float partial) {
        float yaw = net.minecraft.util.Mth.rotLerp(partial, player.yBodyRotO, player.yBodyRot) * ((float) Math.PI / 180);
        Vec3 side = new Vec3(-Math.cos(yaw), 0, -Math.sin(yaw));
        Vec3 shoulder = feet.add(0, player.isCrouching() ? 1.17 : 1.375, 0).add(side.scale(right ? .3125 : -.3125));
        return shoulder.add(target.subtract(shoulder).normalize().scale(.72));
    }
}
